#!/usr/bin/env python3
"""
登录态引导（M0）—— 打开有头浏览器，人工扫码，导出登录态。

产出：
    state/storage_state.json   Playwright 原生登录态（含 localStorage/sessionStorage）
    state/cookie.txt           Netscape 扩展格式（兼容 ../weread-screenshot 的老代码）

用法：
    python3 capture/login.py
    BOOK_URL=... python3 capture/login.py

⚠️ storage_state.json / cookie.txt 含明文登录会话，不要提交到 git。
"""

from __future__ import annotations

import asyncio
import json
import os
import sys
from pathlib import Path

from playwright.async_api import async_playwright

ROOT = Path(__file__).resolve().parent.parent
STATE_DIR = ROOT / "state"
PROFILE_DIR = ROOT / ".browser-profile"
DEFAULT_BOOK_URL = ("https://weread.qq.com/web/reader/"
                    "95332ad0813ab8705g016ce7kc81322c012c81e728d9d180")
BOOK_URL = os.environ.get("BOOK_URL", DEFAULT_BOOK_URL)
VIEWPORT = {"width": 1280, "height": 815}

USER_INFO = ("wr_localvid", "wr_name", "wr_avatar", "wr_gender")


async def login_state(ctx, page) -> dict:
    cookies = await ctx.cookies()
    names = {c["name"] for c in cookies}
    dom = await page.evaluate("""() => {
      const avatar = document.querySelector(
        '[class*="avatar" i], [class*="Avatar"], img[alt*="头像" i], .readerTopBar_right img');
      const loginBtn = [...document.querySelectorAll('a,button,span,div')]
        .filter(e => e.children.length === 0 && (e.innerText || '').trim() === '登录')
        .some(e => { const r = e.getBoundingClientRect(); return r.width > 0 && r.height > 0; });
      return { hasAvatar: !!avatar, loginBtnVisible: loginBtn };
    }""")
    return {"skey": "wr_skey" in names, "vid": "wr_vid" in names, **dom}


def is_logged_in(s: dict) -> bool:
    return s["skey"] and s["vid"] and (s["hasAvatar"] or not s["loginBtnVisible"])


async def main() -> int:
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    print("▶ 启动浏览器（有头，扫码登录）…")
    print(f"  profile: {PROFILE_DIR}")
    print(f"  书籍   : {BOOK_URL}")

    async with async_playwright() as pw:
        ctx = await pw.chromium.launch_persistent_context(
            str(PROFILE_DIR), headless=False, viewport=VIEWPORT, device_scale_factor=1)
        page = ctx.pages[0] if ctx.pages else await ctx.new_page()

        await page.goto(BOOK_URL, wait_until="domcontentloaded", timeout=60000)
        await page.wait_for_timeout(2500)

        st = await login_state(ctx, page)
        print(f"  当前状态: skey={st['skey']} vid={st['vid']} 头像={st['hasAvatar']}")
        if not is_logged_in(st):
            print("\n" + "=" * 60)
            print("  ⚠️  未检测到登录态。请在弹出的浏览器窗口右上角点「登录」，用微信/QQ 扫码。")
            print("  登录完成后本脚本会自动检测并保存。")
            print("=" * 60 + "\n")

        deadline = asyncio.get_event_loop().time() + 10 * 60
        last = 0.0
        while asyncio.get_event_loop().time() < deadline:
            st = await login_state(ctx, page)
            if is_logged_in(st):
                break
            now = asyncio.get_event_loop().time()
            if now - last > 5:
                last = now
                print(f"  …等待登录中  skey={st['skey']} vid={st['vid']} 头像={st['hasAvatar']}")
            await page.wait_for_timeout(2000)

        if not is_logged_in(st):
            print("\n❌ 超时：未检测到登录态。")
            await ctx.close()
            return 1

        print("\n▶ 登录成功，导出登录态…")

        # 先跳书架页让 profile 加载（否则 wr_name/wr_avatar 的 cookie value 为空）
        try:
            await page.goto("https://weread.qq.com/web/bookshelf",
                            wait_until="domcontentloaded", timeout=30000)
            try:
                await page.wait_for_selector(
                    '[class*="avatar" i], [class*="Avatar"], img[alt*="头像" i]', timeout=8000)
            except Exception:
                print("   ⚠️ 等不到头像元素")
            await page.wait_for_timeout(2000)
            await page.goto(BOOK_URL, wait_until="domcontentloaded", timeout=30000)
            await page.wait_for_timeout(1500)
        except Exception as e:
            print(f"   ⚠️ warmup 失败: {e}")

        state_path = STATE_DIR / "storage_state.json"
        await ctx.storage_state(path=str(state_path))
        print(f"   ✅ {state_path}")

        cookies = await ctx.cookies()
        lines = [
            "# Netscape HTTP Cookie File (extended with httpOnly as 8th column)",
            "# Generated by weread-study-agent/capture/login.py — do not edit manually.",
            "# Format: domain  includeSubdomains  path  secure  expires  name  value  [httpOnly]",
            "#",
        ]
        for c in cookies:
            lines.append("\t".join([
                c.get("domain", ""), "TRUE" if c.get("domain", "").startswith(".") else "FALSE",
                c.get("path", "/"), "TRUE" if c.get("secure") else "FALSE",
                str(int(c["expires"])) if c.get("expires") and c["expires"] > 0 else "0",
                c["name"], c["value"], "TRUE" if c.get("httpOnly") else "FALSE",
            ]))
        cookie_path = STATE_DIR / "cookie.txt"
        cookie_path.write_text("\n".join(lines) + "\n", "utf-8")
        print(f"   ✅ {cookie_path}")

        empty = [c["name"] for c in cookies if c["name"] in USER_INFO and not c["value"]]
        if empty:
            print(f"   ⚠️ user-info cookie 为空: {', '.join(empty)}（profile 异步加载所致）")

        paywall = await page.evaluate("""() => {
          const e = document.querySelector('[class*="needPay"]');
          return { has: !!e, text: e ? (e.innerText || '').replace(/\\s+/g, ' ').slice(0, 100) : '' };
        }""")
        if paywall["has"]:
            print(f"   ⚠️ 检测到付费墙（DOM 常驻，不一定拦截翻页）: {paywall['text']}")

        print("\n✅ 登录态已保存。")
        await page.wait_for_timeout(8000)
        await ctx.close()
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
